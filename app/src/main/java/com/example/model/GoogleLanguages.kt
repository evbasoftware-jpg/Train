data class LanguageOption(
  val code: String,
  val nativeName: String,
  val englishName: String,
) {
  val displayLabel: String
    get() = if (nativeName.equals(englishName, ignoreCase = true)) {
      nativeName
    } else {
      "$nativeName ($englishName)"
    }
}

